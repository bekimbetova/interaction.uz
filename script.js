const toggle = document.querySelector('.nav-toggle');
const navLinks = document.querySelector('.nav-links');
const langButtons = document.querySelectorAll('.lang-btn');
const elements = document.querySelectorAll('[data-i18n]');
const placeholderElements = document.querySelectorAll('[data-i18n-placeholder]');
const form = document.getElementById('lead-form');

function applyLanguage(lang) {
  const content = translations[lang] || translations.ru;
  document.documentElement.lang = lang;

  elements.forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const value = key.split('.').reduce((acc, part) => acc && acc[part], content);
    if (typeof value === 'string') {
      element.textContent = value;
    }
  });

  placeholderElements.forEach((element) => {
    const key = element.getAttribute('data-i18n-placeholder');
    const value = key.split('.').reduce((acc, part) => acc && acc[part], content);
    if (typeof value === 'string') {
      element.setAttribute('placeholder', value);
    }
  });

  langButtons.forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === lang);
  });

  localStorage.setItem('interaction-lang', lang);
}

if (toggle && navLinks) {
  toggle.addEventListener('click', () => {
    navLinks.classList.toggle('is-open');
  });

  navLinks.querySelectorAll('a').forEach((link) => {
    link.addEventListener('click', () => navLinks.classList.remove('is-open'));
  });
}

langButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

if (form) {
  form.addEventListener('submit', (event) => {
    event.preventDefault();
    const submitButton = form.querySelector('button[type="submit"]');
    if (submitButton) {
      const currentLang = document.documentElement.lang === 'en' ? 'en' : 'ru';
      const note = currentLang === 'en' ? 'Thanks! We will get back to you soon.' : 'Спасибо! Мы скоро свяжемся с вами.';
      submitButton.textContent = note;
    }
  });
}

const savedLang = localStorage.getItem('interaction-lang');
applyLanguage(savedLang === 'en' ? 'en' : 'ru');
